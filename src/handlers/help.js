const { getUserRole } = require('../utils/permissions');

async function handleHelpCommand(ctx) {
  const role = await getUserRole(ctx);

  if (role === 'owner') {
    const ownerHelp = `👑 راهنمای مالک گروه

سلام مالک محترم! شما به همه امکانات دسترسی دارید. همه دستورات را فقط فارسی و بدون اسلش بنویسید:

⚙️ دستورات مدیریتی مالک:
🔹 افزودن مدیر (ریپلای روی پیام کاربر): اضافه کردن کاربر به مدیرهای ربات
🔹 حذف مدیر (ریپلای روی پیام کاربر): حذف کاربر از مدیرهای ربات
🔹 تنظیم قوانین + متن: مثال: تنظیم قوانین احترام به همدیگر الزامی است
🔹 قوانین: نمایش قوانین فعلی گروه

🛠 امکانات ادمین و عمومی هم برای شما فعال است.
برای دیدن راهنمای اعضا، کلمه راهنما را از یک اکانت دیگر بفرستید.`;

    return ctx.reply(ownerHelp);
  }

  if (role === 'admin') {
    const adminHelp = `🛡 راهنمای مدیر گروه

سلام مدیر محترم! همه دستورات فارسی و بدون اسلش هستند:

🔹 قوانین: نمایش قوانین گروه
🔹 اخطار (ریپلای روی پیام کاربر): دادن اخطار رسمی
🔹 سکوت + تعداد دقیقه (ریپلای): مثال: سکوت ۱۵
🔹 رفع سکوت (ریپلای): برداشتن محدودیت کاربر
🔹 دستیار گزارش: ساخت گزارش تحلیلی امروز گروه

برای راهنمای عمومی اعضا، کلمه راهنما را بفرستید.`;

    return ctx.reply(adminHelp);
  }

  // Member Help — کاملا فارسی، بدون اسلش
  const memberHelp = `🤖 راهنمای دستیار هوشمند گروه

سلام! من دستیار گروه هستم. همه دستورات را فارسی و بدون اسلش بنویسید:

💡 گفتگو با من:
🔹 کلمه دستیار را در پیام بنویسید. مثال: دستیار نظرت درباره این خبر چیه؟
🔹 یا روی پیام من ریپلای بزنید و سوالتان را بنویسید.
🔹 من سبک حرف زدن و تحلیل شما را یادم می ماند!

📰 تحلیل و خبر:
🔹 دستیار تحلیل (ریپلای روی خبر): تحلیل خبر با نکات کلیدی و ریسک ها
🔹 دستیار خلاصه: خلاصه گفتگوهای اخیر گروه
🔹 دستیار پیش بینی + متن: ثبت پیش بینی شما. مثال: دستیار پیش بینی بیت کوین بالا می رود
🔹 پیش بینی های من: دیدن پیش بینی های ثبت شده شما
🔹 دستیار ترجمه یا ترجمه (ریپلای): ترجمه متن
🔹 دستیار ویراستاری یا ویراستاری (ریپلای): اصلاح متن

🎙 ویس:
🔹 روی ویس ریپلای بزنید و بنویسید دستیار یا دستیار تحلیل تا متن کنم و جواب بدهم.

⭐ امتیاز و رتبه:
🔹 ریپلای با متن مثبت یک روی پیام دیگران: دادن امتیاز به آن شخص
🔹 برترین ها یا رتبه بندی یا لیدربورد: جدول بهترین های گروه
🔹 آمار من یا آمار: دیدن امتیاز و فعالیت خودتان

🎮 سرگرمی:
🔹 دستیار قرعه کشی: انتخاب تصادفی یک عضو فعال
🔹 دستیار چیستان
🔹 دستیار جوک
🔹 دستیار نظرسنجی + موضوع: مثال: دستیار نظرسنجی بهترین زمان جلسه کی است`;

  return ctx.reply(memberHelp);
}

module.exports = { handleHelpCommand };
